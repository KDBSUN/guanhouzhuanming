def sheng_triple(att: str, dfd: str, tally: dict = None, month_wx: str = "") -> dict:
    """att 生 dfd 的三值判定：正生 / 母多灭子（生者太过）/ 子旺侮母（受生者太过）。

    同 ke_triple 的写法：设母气 a、子气 d，
      ratio = a / d（d=0 记 +∞；a=d=0 不判）
      ratio 偏大 → **母多灭子**（生得过头，反成埋没／焦炽／漂浊）
      ratio 偏小 → **子旺侮母**（泄得过头，母反被耗／缩／焚／晦）
      落在势均带内 → **正生**

    两边都要判，不能只判"母多灭子"：**只判一侧会漏掉正常格局里最常见的那个错方向**——
    "金生水"若水已泛滥，金反被沉，这时还照说"生得好"就是错的。

    已知局限（写在码里而不是假装没有）：本函数只做**母子两者**的比值，
    不涉及三方通关（"金生水、水又生木"那种链式过量），链式判定仍归流年／调候层。
    """
    from weights import FLOW
    margin = float(FLOW.get("chengwu_margin", 1.0))
    boost_w = float(FLOW.get("month_boost_wang", 1.0))
    boost_x = float(FLOW.get("month_boost_xiang", 0.5))
    tally = tally or {}
    a = float(tally.get(att, 0))
    d = float(tally.get(dfd, 0))
    five = MONTH_FIVE.get(month_wx) if month_wx else None
    if five:
        a += boost_w if five.get(att) == "旺" else (boost_x if five.get(att) == "相" else 0.0)
        d += boost_w if five.get(dfd) == "旺" else (boost_x if five.get(dfd) == "相" else 0.0)
    if a <= 0 and d <= 0:
        return {}
    ratio = round(a / d, 2) if d > 0 else float("inf")
    SRC = "元理赋·反生（图解滴天髓下·反生反克）"

    if a >= d + margin:      # 母太过
        note = ("生者%s气太过：%s生%s而%s过，%s受生不能纳，反成其害" % (att, att, dfd, att, dfd))
        if YUANLI_SHENG_MU.get(att):
            note += "；《元理赋》对证：%s" % YUANLI_SHENG_MU[att]
        return {"value": "母多灭子", "att": att, "dfd": dfd, "ratio": ratio,
                "a": round(a, 2), "d": round(d, 2), "note": note, "src": SRC}

    if d >= a + margin:      # 子太过
        note = ("受生者%s气太过：%s生%s而%s过，%s反被其耗" % (dfd, att, dfd, dfd, att))
        if YUANLI_SHENG_ZI.get(dfd):
            note += "；《元理赋》对证：%s" % YUANLI_SHENG_ZI[dfd]
        return {"value": "子旺侮母", "att": att, "dfd": dfd, "ratio": ratio,
                "a": round(a, 2), "d": round(d, 2), "note": note, "src": SRC}

    return {"value": "正生", "att": att, "dfd": dfd, "ratio": ratio,
            "a": round(a, 2), "d": round(d, 2),
            "note": "%s生%s势均（比值≈1）：相生得宜，母生子而气流通" % (att, dfd),
            "src": SRC}


