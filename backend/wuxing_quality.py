_PAIR_NAME = {frozenset(p): "".join(p) for p in
              [("子", "午"), ("丑", "未"), ("寅", "申"), ("卯", "酉"), ("辰", "戌"), ("巳", "亥"),
               ("子", "丑"), ("寅", "亥"), ("卯", "戌"), ("辰", "酉"), ("巳", "申"), ("午", "未")]}
SAN_HE = {"水": ("申", "子", "辰"), "木": ("亥", "卯", "未"),
          "火": ("寅", "午", "戌"), "金": ("巳", "酉", "丑")}   # 土无三合局
WX_BRANCHES = {"木": ("寅", "卯"), "火": ("巳", "午"), "土": ("辰", "戌", "丑", "未"),
               "金": ("申", "酉"), "水": ("亥", "子")}


def branch_actions(wx: str, zhis) -> list:
    """目标五行的地支（如金=申酉）与命局四支的冲/合/会作用。

    外推类条目（R6 定案）：注记句按固定模板输出（断言主体是"传统"、无量化、
    落点为可执行动作），条目附 出身/接口/边界 三字段元数据，不进裁决。
    """
    zhis = list(zhis or [])
    if not zhis or wx not in WX_BRANCHES:
        return []
    out, seen = [], set()

    def _key(a, b):
        return frozenset((a, b))

    for tb in WX_BRANCHES[wx]:
        for zb in zhis:
            if zb == tb or _key(tb, zb) in seen:
                continue
            if zb == SIX_CHONG.get(tb):
                seen.add(_key(tb, zb))
                pair = _PAIR_NAME.get(_key(tb, zb), "%s%s" % (tb, zb))
                he_partner = SIX_HE.get(tb, "")          # 合住目标支之支（如申被巳合）
                note = (_EXTRAP_TMPL.format(
                    X="%s（与补%s之支%s相冲）" % (zb, wx, tb), Y="散",
                    Z="补%s时可另择时，或在合住之时（%s日合%s）再补；若%s气旺，虽冲不碍"
                      "（《增删卜易·六冲章》）。" % (wx, he_partner, tb, wx)))
                out.append({"type": "六冲", "pair": pair, "note": note,
                            "meta": _EXTRAP_META, "src": "增删卜易·六冲章"})
            elif zb == SIX_HE.get(tb):
                seen.add(_key(tb, zb))
                pair = _PAIR_NAME.get(_key(tb, zb), "%s%s" % (tb, zb))
                hua = HE_HUA.get(pair, "")
                note = (_EXTRAP_TMPL.format(
                    X="%s（与补%s之支%s相合，%s）" % (zb, wx, tb, hua), Y="合绊",
                    Z="补%s时可留意此合的化神（视月令定合化与否），或在冲开之时再补。"
                      % wx))
                out.append({"type": "六合", "pair": pair, "note": note,
                            "meta": _EXTRAP_META, "src": "三命通会·论六合"})
    trio = SAN_HE.get(wx)
    if trio:
        present = [z for z in trio if z in zhis]
        if len(present) == 3:
            note = (_EXTRAP_TMPL.format(
                X="命局%s全（%s三合%s局）" % ("、".join(present), "".join(trio), wx),
                Y="聚气成局", Z="补%s时可把握三支会齐之时安排。" % wx))
            out.append({"type": "三合成局", "pair": "".join(trio), "note": note,
                        "meta": _EXTRAP_META, "src": "子平真诠·会合冲"})
        elif len(present) == 2:
            missing = next(z for z in trio if z not in present)
            note = (_EXTRAP_TMPL.format(
                X="命局%s（%s局之半合，三合以三支全为成局）" % ("、".join(present), wx),
                Y="聚而未成", Z="补%s时可留意%s到位之时（三支全则成局）。" % (wx, missing)))
            out.append({"type": "半合", "pair": "".join(present), "note": note,
                        "meta": _EXTRAP_META, "src": "子平真诠·会合冲"})
    return out
