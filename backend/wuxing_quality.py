def ke_triple(att: str, dfd: str, tally: dict = None, month_wx: str = "") -> dict:
    """att 克 dfd 的三值判定：正克 / 乘（克制过度） / 侮（反克，克制不成立）。

    判据是**攻守比值**（不是单侧绝对量）：设攻气 a、守气 d，
      ratio = a / d（d=0 记 +∞；a=d=0 不判）
      ratio 偏大 → 乘；ratio 偏小 → 侮；落在势均带内 → 正克。
    这样《素问·五运行大论》的四条路径自动坍缩为两态：
      太过侧：气有余则制己所胜（→乘）、侮所不胜（→侮）；
      不及侧：己所不胜侮而乘之（守弱被乘→乘）、己所胜轻而侮之（攻弱受侮→侮）。
    即"乘"可由攻方太过或守方不足触发，"侮"可由守方气足或攻方不足触发——
    单侧阈值会漏掉"不及"两路（如土虚木乘、金衰木侮），比值判据不会。

    典籍背书：势均锚点（中和）为《素问》"制则生化"、《元理赋》"旺而未极"之定性；
    势均带宽度 δ（weights.yaml·flow_thresholds.chengwu_margin）无原文依据，属工程标定。
    乘/侮两侧各有《元理赋》成句对证（见 YUANLI_CHENG / YUANLI_WU）。
    侮态另载经义一句："侮反受邪，侮而受邪，寡于畏也"——发动反克者亦自损，非单方胜利。
    """
    from weights import FLOW
    margin = float(FLOW.get("chengwu_margin", 1.0))
    boost_w = float(FLOW.get("month_boost_wang", 1.0))
    boost_x = float(FLOW.get("month_boost_xiang", 0.5))
    tally = tally or {}
    a = float(tally.get(att, 0))
    d = float(tally.get(dfd, 0))
    five = MONTH_FIVE.get(month_wx) if month_wx else None
