# 八卦侧的同维度类物（📜 另有出处）。**与十干列并列，绝不合并**——见 flavor_split 的说明。
#   阴阳归属据《系辞下》"阳卦多阴，阴卦多阳"：乾（纯阳）、震、坎、艮为阳卦；
#   坤（纯阴）、巽、离、兑为阴卦。
#   金木土各辖两卦（可分明阳），**火只辖离、水只辖坎**（单卦，无从分阴阳）——
#   这不是我们偷懒，是《五行大义》"乾、兑为金，坎为水，震、巽为木，离为火，坤、艮为土"
#   原文如此，必须如实呈现，不能为凑齐两列而编一个。
_GUA_YINYANG = {"乾": "阳", "兑": "阴", "震": "阳", "巽": "阴",
                "坎": "阳", "离": "阴", "艮": "阳", "坤": "阴"}


def flavor_split(wx: str, bagua: dict = None) -> dict:
    """把某五行的建议颗粒按「味」（阴阳）拆成两列，各挂各自的书证。

    `bagua`：`wuxing_xiang.json` 的 bagua 段（卦名 → {五行, 静物, src, …}），可省。

    返回 {"阳": {...}, "阴": {...}, "note": ...}

    ## 为什么是「阴阳」而不是直接写「庚／辛」

    因为两个载体各自独立地给出了这个二分，而**它们之间不能互推**（R6：跨载体不得互推）：
      · 十干载体：《子平真诠》"庚者，阳金也……辛者，阴金也"（《滴天髓》十干体象同）
      · 八卦载体：《系辞下》"阳卦多阴，阴卦多阳" → 乾阳、兑阴
    于是本函数返回**两列并列**：十干列（庚／辛）与八卦列（乾／兑）。
    两列各有出处，谁也不给谁作证。把两列合并成一张"补金之物"清单，
    等于替书上做了它没做过的对应——本项目不干这件事（同"分列两说、各标出处"）。

    ## 火、水只有一列

    火只辖离、水只辖坎，单卦无从分阴阳，故这两行的"八卦列"如实为空并写明原因。
    书上本来就分不出两味的地方，硬凑就是编。

    ## 只拆「物件」，不拆「屋宅」

    八卦侧本来也能给出屋宅的味差（乾"西北向公廨楼台高堂大厦驿舍"／兑"西向近泽、败墙壁宅"），
    **但这里刻意不带**：屋宅是 M 档落地物，S 档契约明写"不要写屋宅布局"。
    而本块挂在顶层维度「质地」下，而「质地」属 S 档——把它塞进来，
    S 档用户就会在自己的建议里读到 M 档内容，越档。屋宅另有自己的顶层维度，
    由档位过滤统一管，不必在这里再开一个口子。
    """
    bagua = bagua or {}
    out = {"阳": None, "阴": None, "note": ""}
    guas = [g for g, b in bagua.items() if (b or {}).get("五行") == wx]
    n_gua_used = 0
    for g in _WX_GANS.get(wx, ()):
        so = STEM_OBJECTS.get(g)
        if not so:
            continue
        key = so["阴阳"]
        col = {"干": g, "名": so["名"], "物": list(so["物"]), "srcs": list(so["srcs"])}
        if so.get("note"):
            col["note"] = so["note"]
        if so.get("润燥"):
            col["润燥"] = so["润燥"]
        # 八卦列：同一阴阳下若该五行辖有此卦，则并挂（各带自己的出处）
        for gua in guas:
            if _GUA_YINYANG.get(gua) == key:
                gb = bagua.get(gua) or {}
                col["卦"] = gua
                col["卦物"] = list(gb.get("静物", []))
                col["卦srcs"] = ["梅花易数·八卦万物属类", "周易·说卦传"]
        out[key] = col
    # 分不动的地方也要说清"分不动"，否则读者会以为是我们漏了
    out["五行级"] = (
        "方位、颜色、数字、五味在书上只给到**五行**这一层，十干不再细分"
        "（《五行大义》\"庚辛、申酉，金也，位在西方\"；五色白、五味辛皆就金言），"
        "故这几项仍是五行级赋值，不硬拆成两列。"
        "乾（西北）与兑（西）的方位差、先天数差属**卦**的属性，不是庚辛之味差——"
        "两者载体不同，不互相折算（R6）。")
    if len(guas) < 2:
        got = _GUA_YINYANG.get(guas[0], "") if guas else ""
        miss = "阴" if got == "阳" else "阳"
        out["note"] = (
            "本行所辖只有一卦（%s），单卦分不出阴阳两列——故【%s】位有卦、【%s】位无卦可对。"
            "《五行大义》\"乾、兑为金，坎为水，震、巽为木，离为火，坤、艮为土\"原文即"
            "金木土各辖两卦、火只辖离、水只辖坎。此处不凑数。"
            % ("、".join(guas) or "—", got or "—", miss))
    return out


# 起卦时令环境的寒燥取向（滴天髓·寒暖 徐注："暖燥太过，喜雨露以润之；寒湿太过，宜太阳以暄之"）
_XUAN_HUO = ("巳", "午", "未", "戌")   # 燥暖之乡
_XUAN_SHUI = ("亥", "子", "丑", "辰")   # 寒湿之地


def pick_flavor(wx: str, month_wx: str = "", day_zhi: str = "", yong_ganzhi: str = "") -> dict:
    """为补某五行挑"哪一味"：卦侧干支优先（六爻用神爻），否则按起卦时令寒燥取向。"""
    if wx not in FLAVOR_TABLE:
        return {}
    stems = _WX_GANS[wx]
    # ① 六爻：用神爻干支直给（干支级，R2）
    if yong_ganzhi:
        gan = next((c for c in yong_ganzhi if c in stems), "")
        if gan:
            return {"gan": gan, "basis": "卦侧用神爻干支",
                    "note": "用神爻%s，取该味（%s）" % (yong_ganzhi, STEMS_TEXTURE[gan]["note"]),
                    "src": "滴天髓·论天干"}
    # ② 时令取向：燥暖宜润、寒湿宜暄
    target = ""
    if month_wx == "火" or day_zhi in _XUAN_HUO:
        target = "润"
        reason = "起卦时令偏燥暖（%s），宜取寒润之味以润之" % (day_zhi or month_wx + "月")
    elif month_wx == "水" or day_zhi in _XUAN_SHUI:
        target = "暖"
        reason = "起卦时令偏寒湿（%s），宜取暖燥之味以暄之" % (day_zhi or month_wx + "月")
    else:
        return {"gan": "", "basis": "时令中和",
                "note": "起卦时令寒燥中和，两味皆可，按所喜择一：%s"
                        % "；".join(FLAVOR_TABLE[wx]["stems"][g] for g in stems),
                "src": "滴天髓·寒暖"}
    # 按标签匹配取向
    def _score(gan):
        t = STEMS_TEXTURE[gan]
        s = 0
        if target == "润":
            s += 2 if ("润" in t["zao_shi"] or "湿" in t["zao_shi"]) else 0
            s += 1 if "寒" in t["han_nuan"] else 0
        else:
            s += 2 if ("燥" in t["zao_shi"] or "暖" in t["han_nuan"]) else 0
            s += 1 if "暖" in t["han_nuan"] else 0
        return s
    best = max(stems, key=_score)
    return {"gan": best, "basis": "起卦时令", "note": "%s；此味取【%s】：%s"
            % (reason, best, FLAVOR_TABLE[wx]["stems"][best]), "src": "滴天髓·寒暖"}


