def hidden_tally(gans, zhis, weights: dict = None) -> dict:
    """干支级五行力量：天干各计 1.0，地支按藏干（本气/中气/余气）加权计。"""
    from weights import FLOW
    w = weights or FLOW.get("hidden_qi_weights") or {"本气": 1.0, "中气": 0.6, "余气": 0.4}
    out = {k: 0.0 for k in WX_ORDER}
    for g in (gans or []):
        if g in GAN_WX:
            out[GAN_WX[g]] += 1.0
    for z in (zhis or []):
        for gan, level in ZHI_CANGGAN.get(z, []):
            out[GAN_WX[gan]] += float(w.get(level, 0.0))
    return {k: round(v, 2) for k, v in out.items()}


