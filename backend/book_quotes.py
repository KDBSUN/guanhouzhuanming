def lookup(key: str) -> dict:
    """出处键 → {book, loc, text, note}；未收录键返回 text=None（原文待录），不代拟。"""
    k = (key or "").strip()
    k = ALIASES.get(k, k)
    for p in _PREFIXES:
        if k.startswith(p):
            q = QUOTES[p]
            return {"key": k, "book": q["book"], "loc": q["loc"], "text": q["text"], "note": ""}
    return {"key": k, "book": k, "loc": "", "text": None,
            "note": "该出处暂未录入原文索引，可在 books/ 库内检索书名核对"}


def lookup_many(keys) -> dict:
    out = {}
    for k in keys:
        k = (k or "").strip()
        if k and k not in out:
            out[k] = lookup(k)
    return out
