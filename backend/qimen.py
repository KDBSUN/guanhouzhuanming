# ---------------- 四、飞盘排盘 ----------------

def qipan_feipan(ju: int, yin_yang: str, day_gz: str, hour_gz: str) -> dict:
    """飞盘奇门排盘（九星九宫顺逆飞、八门不入中五、九神飞布）。"""
    b = _base(ju, yin_yang, day_gz, hour_gz)
    d = b["地盘"]
    P0 = b["时干宫"]
    board = {p: {"宫": p, "地盘": g, "星": [], "天盘": [], "门": None, "神": None}
             for p, g in d.items()}
    # --- 天盘九星：值符加时干宫，其余按洛书序阳顺飞阴逆飞（含中五） ---
    f0 = STAR_FP.index(b["值符"])
