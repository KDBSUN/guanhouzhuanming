    p = P0
    for k in range(1, 9):
        p = _palace_step(p, yin_yang)
        placed[p] = [STAR_FP[(f0 + k) % 9]]
    for p, stars in placed.items():
        board[p]["星"] = stars
        board[p]["天盘"] = [d[STAR_HOME[s]] for s in stars]
    # --- 值使与八门：值使落中五则阳寄艮八、阴寄坤二；门不入中五飞布 ---
    ji_yang, ji_yin = 8, 2
