def pan_geju(pan: dict, dingju: dict, dt=None) -> dict:
    """格局吉凶＋门宫主客。返回 {盘级: [], 九宫: {宫: [{格, 吉凶, 判语}]}, 门宫: {宫: {...}}}。"""
    board = pan["九宫"]
    day_gan, shi_gan = pan["日干支"][0], pan["时干支"][0]
    yi = xunshou(pan["时干支"])[1]
    nian_gan, yue_gan = None, None
    if dt is not None:
        try:
            from lunar_python import Solar
            ec = Solar.fromYmdHms(dt.year, dt.month, dt.day, dt.hour, dt.minute, 0).getLunar().getEightChar()
            nian_gan, yue_gan = ec.getYear()[0], ec.getMonth()[0]
        except Exception:
            pass
    ctx = {"仪": yi, "日干": day_gan, "时干": shi_gan,
           "四干": tuple(x for x in (nian_gan, yue_gan, day_gan, shi_gan) if x),
           "值使": pan["值使"]}
    zf_gong = next((p for p, c in board.items() if pan["值符"] in c["星"]), None)
    zs_gong = next((p for p, c in board.items() if c["门"] == pan["值使"]), None)
    pan_ji = []
    # 盘级：五不遇（时干克日干，法窍凶格注释）
    if KE[GAN_WX[shi_gan]] == GAN_WX[day_gan]:
        pan_ji.append({"格": "五不遇", "吉凶": "凶", "判语": "出行主损折不利，百事皆凶，用兵尤忌"})
    # 伏吟/返吟（星符门还加本宫/对冲之宫，法窍凶格注释）
    if zf_gong is not None and zs_gong is not None:
        zf_ben = STAR_HOME[pan["值符"]]
        men_home = {v: k for k, v in (GONG_MEN if pan["盘式"] == "转盘" else GONG_MEN_FP).items()}
        zs_ben = men_home.get(pan["值使"])
        if zf_gong == zf_ben and zs_gong == zs_ben:
            pan_ji.append({"格": "伏吟", "吉凶": "凶", "判语": "百事不遂，惟宜收敛财货；进兵必遭围困"})
        if zf_gong == GONG_CHONG[zf_ben] or zs_gong == GONG_CHONG[zs_ben]:
            pan_ji.append({"格": "返吟", "吉凶": "凶", "判语": "只宜发粮散饷，最忌行兵，主反覆不宁"})
    # 逐宫
    geju9, mengong = {}, {}
    for p in range(1, 10):
        c = board.get(str(p)) or board.get(p)
        if not c:
            continue
        found = []
        for t_gan in c["天盘"]:
            for name, jx, yu, cond in GAN_GEJU:
                if cond(t_gan, c["地盘"], ctx):
                    found.append({"格": name, "吉凶": jx, "判语": yu})
        for name, jx, yu, cond in GONG_GEJU:
            if cond(c, ctx):
                found.append({"格": name, "吉凶": jx, "判语": yu})
        if found:
            geju9[p] = found
        if c["门"]:
            mengong[p] = men_gong_pan(c)
    return {"盘级": pan_ji, "九宫": geju9, "门宫": mengong}


