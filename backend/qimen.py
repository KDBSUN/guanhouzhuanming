def dipan(ju: int, yin_yang: str) -> dict:
    """地盘三奇六仪：戊己庚辛壬癸丁丙乙，阳顺阴逆布九宫（含中五）。"""
    d, p = {}, ju
    for g in "戊己庚辛壬癸丁丙乙":
        d[p] = g
        if yin_yang == "阳遁":
            p = p + 1 if p < 9 else 1
        else:
            p = p - 1 if p > 1 else 9
    return d


def _palace_step(p: int, yin_yang: str) -> int:
    """按九宫数字顺（阳）/逆（阴）走一步，含中五（值使计数与飞盘星飞用）。"""
    if yin_yang == "阳遁":
        return p + 1 if p < 9 else 1
    return p - 1 if p > 1 else 9


def _palace_step_skip5(p: int, yin_yang: str) -> int:
    """按九宫数字顺/逆走一步，跳过中五（飞盘八门飞布用；阳 4→6、阴 6→4）。"""
    if yin_yang == "阳遁":
        return 6 if p == 4 else (p + 1 if p < 9 else 1)
    return 4 if p == 6 else (p - 1 if p > 1 else 9)


def zhishi_gong(yi_gong: int, xun_gz: str, hour_zhi: str,
                yin_yang: str, ji_yang: int, ji_yin: int) -> int:
    """值使门落宫：从旬首宫起旬首，阳顺阴逆数宫至时支；落中五则寄宫。

    ji_yang/ji_yin 为落中五时的寄宫（转盘寄坤二坤二；飞盘阳寄艮八、阴寄坤二）。
    """
    dist = (ZHI.index(hour_zhi) - ZHI.index(xun_gz[1])) % 12
    p = yi_gong
    for _ in range(dist):
        p = _palace_step(p, yin_yang)
    if p == 5:
        p = ji_yang if yin_yang == "阳遁" else ji_yin
    return p


def _base(ju: int, yin_yang: str, day_gz: str, hour_gz: str) -> dict:
    """定局之后、两盘共用的起局信息。"""
    d = dipan(ju, yin_yang)
    sg = hour_gz[0]
    xun, yi = xunshou(hour_gz)
    yi_gong = next(p for p, g in d.items() if g == yi)
    if sg == "甲":
        # 六甲时：时干甲遁于本旬之仪，时干宫＝旬首遁仪所在宫（甲不显于盘）
        shigan_gong = yi_gong
    else:
        shigan_gong = next(p for p, g in d.items() if g == sg)
    zhifu = GONG_STAR[yi_gong]
    if yi_gong == 5:
        # 甲辰壬落中五：禽星为直符，寄宫之门为直使（法窍 L989）
        # 转盘寄坤二（秘笈大全 L31 天禽寄西南）→死门；飞盘阳寄艮八→生门、阴寄坤二→死门
        zhishi_zp = "死"
        zhishi_fp = "生" if yin_yang == "阳遁" else "死"
    else:
        zhishi_zp = GONG_MEN[yi_gong]
        zhishi_fp = GONG_MEN_FP[yi_gong]
    return {
        "地盘": d, "时干宫": shigan_gong, "旬首": xun, "旬首遁仪": yi,
        "旬首宫": yi_gong, "值符": zhifu, "值使(转盘)": zhishi_zp, "值使(飞盘)": zhishi_fp,
        "日干支": day_gz, "时干支": hour_gz,
    }


