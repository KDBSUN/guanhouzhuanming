def _jieqi_timeline(year: int) -> list:
    """T 所在年前后交节时刻全表（精确到秒），按时间排序，元素 (节气名, datetime)。

    lunar_python 的 getJieQiTable 以农历年为界、冬至为首（某农历年的表从上年冬至排到
    当年大雪），故要收集 T 所在公历年前后各一个农历年的表再取并集。
    """
    from lunar_python import Solar
    seen, out = set(), []
    for ly in (year - 1, year, year + 1, year + 2):
        try:
            table = Solar.fromYmdHms(ly, 6, 1, 12, 0, 0).getLunar().getJieQiTable()
        except Exception:
            continue
        for name, s in table.items():
            if name not in JIEQI_ORDER:
                continue
            dt = datetime(s.getYear(), s.getMonth(), s.getDay(),
                          s.getHour(), s.getMinute(), s.getSecond())
            key = (name, dt)
            if key in seen:
                continue
            seen.add(key)
            out.append((name, dt))
    out.sort(key=lambda x: x[1])
    return out


def day_gz_rolled(dt: datetime) -> str:
    """时家口径的日干支：23 点起算次日（子时换日）。"""
    from lunar_python import Solar
    y, m, d = dt.year, dt.month, dt.day
    if dt.hour >= 23:
        d += 1
    return Solar.fromYmdHms(y, m, d, 12, 0, 0).getLunar().getDayInGanZhi()


def shichen_gz(day_gz: str, hour: int) -> str:
    """五子元遁起时：甲己日起甲子、乙庚丙子、丙辛戊子、丁壬庚子、戊癸壬子。

    day_gz 须已按子时换日口径折算（23 点归次日）。
    """
    zi = ((hour + 1) // 2) % 12  # 23→0子, 0→0子, 1→1丑
    start = (GAN.index(day_gz[0]) % 5) * 2
    return GAN[(start + zi) % 10] + ZHI[zi]


def xunshou(hour_gz: str) -> tuple:
    """时柱旬首。返回 (旬首干支, 旬首所遁六仪)。

    六甲遁仪：甲子同戊、甲戌同己、甲申同庚、甲午同辛、甲辰同壬、甲寅同癸。
    """
    idx = GZ60.index(hour_gz)
    xun_idx = idx - idx % 10
    xun_gz = GZ60[xun_idx]
    yi = {"子": "戊", "戌": "己", "申": "庚", "午": "辛", "辰": "壬", "寅": "癸"}[xun_gz[1]]
    return xun_gz, yi


def dingju(dt: datetime, _jieqi: list | None = None) -> dict:
    """拆补法定局。

    规则（法窍 L953/L3297；启悟 L553–555）：
    1. 以交节时刻定节气（交节时刻前一时辰段属上一节气）；
    2. 甲己日为符头，五日一元，符头日支定元（子午卯酉上、寅申巳亥中、辰戌丑未下）；
    3. 该元落在哪个节气内，就用哪个节气的局（残局＝节前符头统领之元入本节气，
       补局＝节末未满五日之元仍用本节气之局）。
    _jieqi 供测试注入（元素 (节气名, 交节datetime) 升序）。
    """
    if _jieqi is None:
        _jieqi = _jieqi_timeline(dt.year)
    cur_name, cur_dt, next_dt, next_name = None, None, None, None
    for i, (name, t) in enumerate(_jieqi):
        if t <= dt:
            cur_name, cur_dt = name, t
            if i + 1 < len(_jieqi):
                next_name, next_dt = _jieqi[i + 1]
        else:
            break
    if cur_name is None:  # 早于表内最早交节：按表首节气的阴遁/阳遁口径退回上一年
        name0, t0 = _jieqi[0]
        # 极端罕见，直接按表首处理并标注
        cur_name, cur_dt, next_name, next_dt = name0, t0, None, None

    day_gz = day_gz_rolled(dt)
    day_idx = GZ60.index(day_gz)
    futou_idx = day_idx - day_idx % 5  # 本五日之元的符头（甲/己日）
    futou = GZ60[futou_idx]
    yuan_idx = (futou_idx // 5) % 3  # 0上 1中 2下（甲子块上、己巳块中、甲戌块下……）
    yuan = YUAN_NAMES[yuan_idx]
    ju = JU_TABLE[cur_name][yuan_idx]
    yin_yang = "阳遁" if cur_name in YANGDUN else "阴遁"
    hour_gz = shichen_gz(day_gz, dt.hour)
    return {
        "节气": cur_name,
        "阴阳遁": yin_yang,
        "元": yuan,
        "局数": ju,
        "符头": futou,
        "日干支": day_gz,
        "时干支": hour_gz,
        "交节时刻": cur_dt.strftime("%Y-%m-%d %H:%M:%S") if cur_dt else "",
        "下一节气": next_name or "",
        "下一交节时刻": next_dt.strftime("%Y-%m-%d %H:%M:%S") if next_dt else "",
        "定局法": "拆补法",
    }


