def wulei_query(kind: str, name: str) -> dict:
    """物类表查询：kind='支神'（子…亥）或 '天将'（贵人…天后）。"""
    if kind == "支神":
        z = ZHI_MING.get(name, name)
        d = ZHISHEN.get(z)
        if not d:
            return {"口径": "未查到该支神物类", "候选": []}
        return {"口径": "十二支神物类（说约卷上十二天神为主，心镜杂神门、苗公十二时照显变化论为参）",
                "支": z, **d}
    if kind == "天将":
        j = JIANG_ALIAS.get(name, name)
        d = TIANJIANG.get(j)
        if not d:
            return {"口径": "未查到该天将物类", "候选": []}
        return {"口径": "十二天将物类（说约卷上十二天将为主，心镜杂将门、苗公十二贵人照显变化论为参）",
                "将": j, **d}
    return {"口径": "kind 须为 支神/天将", "候选": []}

