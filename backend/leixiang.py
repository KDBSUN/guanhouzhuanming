def _tianma(jian_zhi: str) -> str:
    """六壬天马：正月午顺行六阳辰（大全 L2876「天马，正月午，顺行六阳辰」；
    L7942 同）。说约二马＝驿马+天马。"""
    if jian_zhi is None:
        return ""
    yue = (ZHI.index(jian_zhi) - ZHI.index("寅")) % 12 + 1
    return "午申戌子寅辰"[(yue - 1) % 6]


def _liuqin_zhi(day_gan: str, liu: str) -> list:
    """全盘十二支中六亲为 liu 者（财爻/官爻/父爻/子孙爻/比肩爻/荫爻/官鬼）。"""
    from daliuren import liuqin
    return [z for z in ZHI if liuqin(day_gan, [z])[0] == liu]


def _resolve_token(ke: dict, token: str) -> list:
    """把类神记号解析为盘上地支候选（全盘口径）。"""
    day_gan, day_zhi = ke["日干支"][0], ke["日干支"][1]
    tp, tianj = ke["天盘"], ke["天将"]
    if token in ZHI_MING:
        return [ZHI_MING[token]]
    if token in TIANJIANG:
        return [z for z, j in tianj.items() if j == token]
    if token in JIANG_ALIAS:
        return [z for z, j in tianj.items() if j == JIANG_ALIAS[token]]
    liu = {"财爻": "妻财", "官爻": "官鬼", "父爻": "父母", "子孙爻": "子孙",
           "比肩爻": "兄弟", "荫爻": "父母", "官鬼": "官鬼", "日鬼": "官鬼"}.get(token)
    if liu:
        return _liuqin_zhi(day_gan, liu)
    if token == "长生":
        return [GAN_CS[day_gan][0]]
    if token == "日德":
        return [GAN_DE[day_gan]]
    if token == "驿马":
        return [MA[day_zhi]]
    if token == "二马":
        jian = ke.get("月建")
        out = [MA[day_zhi]]
        tm = _tianma(jian) if jian else ""
        if tm:
            out.append(tm)
        return out
    if token == "丁神":
        day_gz = ke["日干支"]
        xun_zhi = GZ60[GZ_INDEX[day_gz] - GZ_INDEX[day_gz] % 10][1]
        return [ZHI[(ZHI.index(xun_zhi) + 3) % 12]]
    if token == "幕贵":
        from daliuren import GUIREN
        zhou = ke["占时"] in "卯辰巳午未申"
        return [GUIREN[day_gan][1 if zhou else 0]]
    if token in ("传送外场", "太乙外场", "驿马外场", "朱雀内场", "贵人内场"):
        return _resolve_token(ke, token[:-2])
    return []


def leishen_qiyong(ke: dict, wenshi: str, nianming: dict | None = None) -> dict:
    """类神取用：通类天将（壬归）＋事类神（说约类神说）＋盘上类神状态（只标事实）。"""
    tp = ke["天盘"]
    inv = {v: k for k, v in tp.items()}
    sk = tp[JIGONG[ke["日干支"][0]]]
    zs = tp[ke["日干支"][1]]
    chuan = ke["三传"]
    tonglei = TONGLEI.get(wenshi, "")
    items = []
    seen = set()
    tokens = SHILEI.get(wenshi) or ([tonglei] if tonglei else [])
    for token in tokens:
        for z in _resolve_token(ke, token):
            if z in seen:
                continue
            seen.add(z)
            status = []
            gong = inv.get(z)
            status.append(f"天盘落{gong or '?'}宫（{GONG_FANG.get(gong, '中')}）")
            if z in chuan:
                status.append(f"入传（{'初' if z == chuan[0] else '中' if z == chuan[1] else '末'}传）")
            if z == sk:
                status.append("临干上")
            if z == zs:
                status.append("临支上")
            if nianming:
                for who, w in (("本命", nianming.get("本命")), ("行年", nianming.get("行年"))):
                    if w and tp.get(w) == z:
                        status.append(f"临{w}上")
            # 与干上神/年命上神之生克合冲刑害（说约类神变化规则口径，只标事实）
            guan = []
            for base, name in ((sk, "干上神"),):
                if z == base:
                    continue
                if SHENG[ZHI_WX[z]] == ZHI_WX[base]:
                    guan.append(f"生{name}")
                elif SHENG[ZHI_WX[base]] == ZHI_WX[z]:
                    guan.append(f"{name}生我")
                elif KE[ZHI_WX[z]] == ZHI_WX[base]:
                    guan.append(f"克{name}")
                elif KE[ZHI_WX[base]] == ZHI_WX[z]:
                    guan.append(f"被{name}克")
                elif LIUHE.get(z) == base:
                    guan.append(f"与{name}六合")
                elif CHONG.get(z) == base:
                    guan.append(f"冲{name}")
                elif XING.get(z) == base or XING.get(base) == z:
                    guan.append(f"刑{name}")
            if not status:
                status.append("不入传、不临干上支上")
            items.append({"记号": token, "类神": z, "名": ZHISHEN.get(z, {}).get("名", z),
                          "状态": status, "与干上": guan})
    return {"问事": wenshi, "通类天将": tonglei, "通类据": TONGLEI_RULE,
            "类神": items, "取类规则": SHILEI_RULE,
            "口径": "只标盘面事实，不代断（类神变化规则见说约类神说）"}


