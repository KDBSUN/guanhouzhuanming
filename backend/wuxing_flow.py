#
# 典籍依据（逐字回源，文本在 D:\Web\books\bazimingli）：
#   《图解滴天髓·下部》引徐大升《元理赋》「常理和变理」一组，共二十句，
#   该书把它明确定名为**反生反克**：
#     「金能克木，木坚金缺。木能克土，土重木折。土能克水，水多土流。
#       水能克火，火炎水热。火能克金，金多火熄。金衰遇火，必见销熔。
#       火弱逢水，必为熄灭。水弱逢土，必为淤塞。土衰遇木，必遭倾陷。
#       木弱逢金，必为砍折。」
#   同书另一处点出反克的成立条件："五行**得势**反克它的五行……本来金克木，
#   但是**木得势**，就会反克金"——"得势"即守方气足，正是 ke_triple 判「侮」的
#   `d >= a + margin`。故《元理赋》的"反克"与《素问》的"侮"**判据同源**
#   （ke_triple 自己的 docstring 亦写作"侮（反克，克制不成立）"）。
#
#   而「从格/中和偏旺」一侧的「忌」，依据在**格局顺逆**，与反克无关：
#   《穷通宝鉴评注》："若变局，格成专旺，名曰从革，不欲见火。运喜西北，忌东南。"
#   《滴天髓·专旺五格》：曲直"忌西方"、炎上"忌西北"、从革"忌南方"、
#                         稼穑"忌东北"、润下"忌东南"。
#   这一类是"此克确实有害（会破格）"＝有效，与"克不成立"**方向相反**，故仍应告警。
#
# 下面逐条列出**属于《元理赋》反生反克组**的格位（(五行, 状态, 关系位)）。
# 判定与实现都已实测核对（探针：静态枚举 26 条 grade∈{忌,大忌} 的克边，
# 动态构造命局逼出「侮」，实出告警 21 条 → 其中 15 条落在本集合内，6 条不在）。
# 未列入者一律照旧告警——**宁可多报，不可漏报**。
ANTI_KE_CELLS = {
    # —— 前五句「X能克Y，Y坚X缺」型 → 落在「我克」边 ——
    ("金", "弱", "我克"), ("金", "弱极", "我克"),    # 金能克木，木坚金缺
    ("木", "弱", "我克"), ("木", "弱极", "我克"),    # 木能克土，土重木折
    ("土", "弱", "我克"), ("土", "弱极", "我克"),    # 土能克水，水多土流
    ("水", "弱", "我克"), ("水", "弱极", "我克"),    # 水能克火，火炎水热（本表判词取《穷通宝鉴·论水》"水受渴"，同组）
    ("火", "弱", "我克"), ("火", "弱极", "我克"),    # 火能克金，金多火熄
    # —— 后五句「X衰遇Y」型 → 落在「克我」边 ——
    ("金", "弱", "克我"),                            # 金衰遇火，必见销熔
    ("火", "弱", "克我"),                            # 火弱逢水，必为熄灭
    ("水", "弱", "克我"), ("水", "弱极", "克我"),    # 水弱逢土，必为淤塞
    ("土", "弱", "克我"), ("土", "弱极", "克我"),    # 土衰遇木，必遭倾陷
    ("木", "弱", "克我"),                            # 木弱逢金，必为砍折
}
# 注：木/火/金 的「弱极·克我」不在上列——那三格的判词是"弱极不任克，顺势（从格）另判"
# （《滴天髓·阴阳颠倒》），属**从格**一路而非反克，与「侮」不同源，故照旧告警。
# 又：这五格在「弱极」档因本五行计数为 0（d=0），实际永远判不出「侮」，不会触发告警。


def _rel_wx(wx: str, rel: str) -> str:
    return {"进气": MOTHER[wx], "出水": SHENG[wx], "我克": KE[wx], "克我": KEME[wx]}[rel]


def state_score(wx: str, mingju: dict) -> float:
    """状态分档的判据值（命局数量 + 母气半分 + 月令加成）——供边界样本记账用。"""
    tally = (mingju or {}).get("wuxing_tally") or {}
    month_wx = (mingju or {}).get("month_wx") or ""
    n = tally.get(wx, 0)
    if month_wx == wx:
        ling = 1.0
    elif month_wx and SHENG.get(month_wx) == wx:
        ling = 0.5
    else:
        ling = 0.0
    return round(n + 0.5 * tally.get(MOTHER[wx], 0) + ling, 2)


def classify_state(wx: str, mingju: dict):
    """目标五行状态分档：弱极 / 弱 / 中和偏旺 / 旺极(从格)。显示层分类。"""
    tally = (mingju or {}).get("wuxing_tally") or {}
    month_wx = (mingju or {}).get("month_wx") or ""
    from_ge = (mingju or {}).get("from_ge") or ""
    # 专旺/化气格局：目标即格局五行 → 直接顺其势
    if from_ge and (from_ge.startswith("专旺") or from_ge.startswith("化气")):
        if wx == (mingju or {}).get("effective_wx"):
            return "旺极(从格)", "命局已判【%s】，顺其旺势取用（一行专用，不再堆补）" % from_ge
    n = tally.get(wx, 0)
    if month_wx == wx:
        ling = 1.0
    elif month_wx and SHENG.get(month_wx) == wx:
        ling = 0.5
    else:
        ling = 0.0
    score = n + 0.5 * tally.get(MOTHER[wx], 0) + ling
    th = FLOW  # R4：阈值全部来自 weights.yaml（v1.1.0 起入池，可版本化、可做敏感度分析）
    if n == 0 or score < float(th.get("state_jiruo_max", 1.0)):
        return "弱极", "命局几乎不见此五行（虚不受补，专用式/顺势扶持）"
    if score < float(th.get("state_weak_max", 3.0)):
        return "弱", "此五行在命局偏少又不得月令，宜补而量少"
    if score < float(th.get("state_strong_min", 6.0)):
        return "中和偏旺", "此五行有根有源力量偏旺而未成势：留出口、防过补"
    return "旺极(从格)", "此五行成势（多且当令），按专旺思路顺其势"


def _tongguan_hits(wx: str, tally: dict) -> list:
    """通关命中说明（有命局数据时）：克我对峙 / 我克对峙 两个方向。"""
    hits = []
    kem = KEME[wx]
    if tally.get(kem, 0) >= 2 and tally.get(wx, 0) >= 1:
        m = MOTHER[wx]
        hits.append("命中：局中%s与%s对峙 → 添%s通关（%s生%s、%s生%s），化攻为生"
                    % (kem, wx, m, kem, m, m, wx))
    kobj = KE[wx]
    if tally.get(kobj, 0) >= 2 and tally.get(wx, 0) >= 2:
        m2 = SHENG[wx]
        hits.append("命中：局中%s与%s对峙 → 添%s通关（%s生%s、%s生%s），化战为通"
                    % (wx, kobj, m2, wx, m2, m2, kobj))
    return hits


def flow_plan(wx: str, mingju: dict = None, day_zhi: str = "", yong_ganzhi: str = "") -> dict:
    """目标五行 → 流动五行整表（表头 + 强弱四档行 + 通关行 + 质别 + 阴阳细分 + 质地取向）。

    强弱四档**全部返回**，只有命中那档 `active=True`；前端默认只显示命中行，另有
    "查看全部档位"展开。乘侮/生害（边态）只挂在命中档上，理由见下方循环内的注释。

    mingju 为命局基线（mingju dict）；为 None/空时仍出表头与通关行，只是不判强弱。
    day_zhi/yong_ganzhi 为卦侧干支层（R2）：六爻传用神爻干支，梅花传起卦日支，用于质地取向。
    """
    if wx not in WX_ORDER:
        raise ValueError("未知五行: %r" % wx)
    mingju = mingju or {}
    tally = mingju.get("wuxing_tally") or {}
    has_profile = bool(tally)

    if has_profile:
        state, state_note = classify_state(wx, mingju)
    else:
        state, state_note = None, "未提供命局档案：不判定强弱档（下方仅列通关规则）"

    header = {rel: "%s（%s·%s）" % (rel, _rel_wx(wx, rel), _REL_META[rel]) for rel in _RELS}

    rows = []
    # 无档案时**一行强弱都不出**：四档全出是为了让用户能对照"我不是这一档的话会怎样"，
    # 而没有命局就连"我在哪一档"都不知道——给四行假设等于让他对着四个可能猜。
    for st in STATES if state is not None else ():
        # 四档全出，但只有命中那档标 active。**为什么要全出**：只给命中行的话，
        # 用户没有任何东西可对照——分错一档就是整行建议错，而他看不见错在哪。
        # 全出之后他能自己看："若我是中和偏旺，这几条会变成什么"。
        is_active = (st == state)
        row = TABLE[wx][st]
        cells = {}
        for rel in _RELS:
            grade, note, src = row[rel]
            cells[rel] = {"grade": grade, "note": note, "src": src}
        rows.append({"state": st, "cells": cells, "active": is_active})

    # 通关行（静态整表行，按用户表格式：出水列给通关，余列"—"；有命局时附命中说明）
    tg_src = {"金": "子平真诠·通关", "木": "子平真诠·通关", "火": "滴天髓·通关",
              "土": "滴天髓·通关", "水": "子平真诠·通关"}[wx]
    m2, kobj = SHENG[wx], KE[wx]
    m1, kem = MOTHER[wx], KEME[wx]
    tg_note = "我克对峙（局中%s多）：添%s通关（%s→%s→%s）；克我对峙（局中%s旺）：添%s通关（%s→%s→%s）" % (
        kobj, m2, wx, m2, kobj, kem, m1, kem, m1, wx)
    rows.append({
        "state": "局中交战",
        "cells": {
            "进气": None,
            "出水": {"grade": "视情况", "note": tg_note, "src": tg_src},
            "我克": None,
            "克我": None,
        },
        "active": False,
        "hits": _tongguan_hits(wx, tally) if has_profile else [],
    })

    qualities = [{"note": t, "src": s} for t, s in TABLE[wx]["_质别"]]
    qualities += [{"note": t, "src": s} for t, s in GENERAL_NOTES]

    # —— 第二批·关系层接入（乘侮/月令五态/干支作用，均显示层校验） ——
    month_wx = mingju.get("month_wx") or ""
    m5 = month_state(wx, month_wx) if month_wx else {}
    # R2：乘侮升级为干支级——有藏干加权力量（wuxing_tally_hidden）就用它，否则退化为五行计数
    ke_tally = mingju.get("wuxing_tally_hidden") or tally
    if has_profile and state:
        for r in rows:
            # 乘侮与生害只挂在**命中档**上：它们是按这盘的真实力量分布算的（ke_tally），
            # 磨的是"你这一档的方向该加多少量"。挂到假设档上等于说"你若换一档，
            # 量级修正也是这个"——那是错的，且会让人误以为四行都是给他的断语。
            if not r["active"]:
                continue
            for rel, att, dfd in (("我克", wx, KE[wx]), ("克我", KEME[wx], wx)):
                cell = r["cells"].get(rel)
                if not cell:
                    continue
                cw = ke_triple(att, dfd, ke_tally, month_wx)
                cell["chengwu"] = cw
                # R5 消解：乘侮是静态格的"量级调制器"——方向由静态格给，量级/时机由边态修正。
                # 不新设优先级体系：同一条克边上判出乘/侮时，禁止静态格裸输出，改出复合句。
                if cw and cw.get("value") in ("乘", "侮"):
                    grade = cell.get("grade", "")
                    opens = grade in ("首选", "专用", "宜", "宜少量", "改补同类")   # 静态格"开此克"
                    if cw["value"] == "乘":
                        fix = "克制过度：须减%s，或添%s通关" % (att, MOTHER[dfd])
                    else:
                        fix = "克制不成立：须增%s（并防'侮反受邪'之自损），或添%s通关" % (att, MOTHER[dfd])
                    cell["combined"] = "方向：%s｜量级修正：%s（%s）" % (grade, cw["value"], fix)
                    # 真冲突＝两处判断**方向相反**才值得复核；同向确认不出告警。
                    #   · 静态格「开」此克 而 边态判「乘」（火本不够格却已过头）→ 相反 ✓告警
                    #   · 静态格「忌」此克 而 边态判「侮」，且该格**不属**《元理赋》反生反克组
                    #     （即"忌"的理由是逆势/破格这类"此克有效且有害"）→ 相反 ✓告警
                    #   · 若该格属反克组，则"忌"的理由本就是"克不动、反受其伤"，
                    #     与「侮」是同一个判断 → 同向，不告警（见 ANTI_KE_CELLS 的典籍依据）
                    anti_ke = (wx, r["state"], rel) in ANTI_KE_CELLS
                    cell["conflict"] = bool((opens and cw["value"] == "乘") or
                                            (grade in ("忌", "大忌") and cw["value"] == "侮"
                                             and not anti_ke))
                    if anti_ke and cw["value"] == "侮":
                        # 不静默略过：把"为什么这次不告警"记下来，便于回查（R5 的取向是
                        # "不静默择一"，压制告警同样要说清理由，而不是悄悄少报一条）
                        cell["conflict_suppressed"] = (
                            "静态格「%s」与边态「侮」同源：两者皆判此克不成立"
                            "（《元理赋》反生反克组），非方向冲突，故不告警。" % grade)
                    if cell["conflict"]:
                        cell["conflict_note"] = ("静态格（%s）与边态（%s）不同源：请复核行态快照"
                                                 "（命局档位/力量分布）后再定建议" % (grade, cw["value"]))

            # R11：生边三值化（母多灭子／子旺侮母）——与克边**同构**，用同一个势均带。
            #   进气＝母生我（MOTHER[wx] → wx）；出水＝我生子（wx → SHENG[wx]）。
            # 在补之前，这两条边只会说"能生，好"，说不出「土多金埋」「水多金沉」——
            # 而那正是辅助场景里最容易给错方向的地方（生得过头、泄得过头都成害）。
            for rel, att, dfd in (("进气", MOTHER[wx], wx), ("出水", wx, SHENG[wx])):
                cell = r["cells"].get(rel)
                if not cell:
                    continue
                sg = sheng_triple(att, dfd, ke_tally, month_wx)
                cell["sheng_three"] = sg
                # 生边不设"冲突告警"：生害（母多灭子／子旺侮母）与静态格不是两套结论，
                # 而是**同一方向的量级修正**——故直接出复合句，不引入 R5 那类复核告警。
                if sg and sg.get("value") in ("母多灭子", "子旺侮母"):
                    cell["combined"] = "方向：%s｜生害修正：%s（%s）" % (
                        cell.get("grade", ""), sg["value"], sg["note"])
    zhis = mingju.get("zhis") or []
    gans = mingju.get("gans") or []
    branch_notes = branch_actions(wx, zhis) if zhis else []
    stem_notes = stem_actions(wx, gans) if gans else []      # R2：天干五合（干侧作用）
    # R2/R1：卦侧干支优先（六爻用神爻），否则按起卦时令寒燥取向
    flavor = pick_flavor(wx, month_wx=month_wx, day_zhi=day_zhi or "",
                         yong_ganzhi=yong_ganzhi or "")

    return {
        "wx": wx,
        "header": header,
        "state": state,
        "state_note": state_note,
        "state_score": state_score(wx, mingju) if has_profile else None,
        "month_state": m5,
        "branch_notes": branch_notes + stem_notes,
        "branch_missing": bool(has_profile) and not zhis,
        "flavor": flavor,
        "rows": rows,
        "tongguan_src": tg_src,
        "qualities": qualities,
        # 阴阳细分（建议区内直接可见）：该五行一对天干的 药性/寒暖/燥湿 + 十干体象书证
        "yinyang": {
            "items": [dict(gan=g, **stem_texture(g)) for g in WX_STEMS[wx]],
            "placeholder": "",
        },
    }
