def yunqi(ganzhi: str) -> dict:
    """某一干支年的五运六气结构（改运链·天地气背景）。

    ganzhi：干支年（如「丁亥」）。返回：中运（五音/五行/太过不及）、司天、在泉、
    天符/岁会/同天符/太乙天符、化数（医家原文的生成数）、药食宜、胜复与灾宫（表有则记）。
    本模块不输出吉凶档位。
    """
    g, z = ganzhi[0], ganzhi[1]
    wx = GAN_YUN[g]
    tai = g in YANG_GAN
    yun5 = ("太" if tai else "少") + WUYIN[wx]
    si, zai = SIZAI[[k for k in SIZAI if z in k][0]]
    si_wx, zai_wx = LIUQI_WX[si], LIUQI_WX[zai]
    # 天符＝中运与司天之气同；岁会＝中运与年支五行同；同天符＝太过之中运与在泉之气同；
    # 太乙天符＝天符且岁会（天元纪大论定义）
    flags = []
    if wx == si_wx:
        flags.append("天符")
    if wx == ZHI_WX[z]:
        flags.append("岁会")
    if tai and wx == zai_wx:
        flags.append("同天符")
    if "天符" in flags and "岁会" in flags:
        flags = ["太乙天符"]
    pair = _YEAR_PAIR.get(ganzhi) or {}
    out = {
        "ganzhi": ganzhi,
        "中运": {"五音": yun5, "五行": wx, "太过不及": "太过" if tai else "不及"},
        "司天": si, "在泉": zai,
        "司天五行": si_wx, "在泉五行": zai_wx,
        "特殊": flags,
        "label": pair.get("label", ""),
    }
    if pair:
        out["化数"] = pair["hua"]
        out["药食宜"] = pair["yi"]
        if pair.get("shengfu"):
            out["胜复"] = pair["shengfu"]
            out["灾宫"] = pair["zai_gong"]
        out["书证"] = "《素问·六元正纪大论》" + pair["label"]
    return out


def buqi(ganzhi: str, year: int | None = None) -> list:
    """该年六步：主气（年年不变）＋客气（司天居三之气）＋客主加临。

    返回六步列表，每步含：步名、主气、客气、主气五行、客气五行、主气说明、起始节气
    （给 year 时补公历起日）。
    """
    BU_NAMES = ["初之气", "二之气", "三之气", "四之气", "五之气", "终之气"]
    si, _ = SIZAI[[k for k in SIZAI if ganzhi[1] in k][0]]
    i3 = LIUQI_ORDER.index(si)
    steps = []
    for j in range(6):
        zhu = ZHUQI[j]
        ke = LIUQI_ORDER[(i3 + j - 2) % 6]      # 三之气＝司天，前后依三阴三阳次序
        step = {
            "步": BU_NAMES[j],
            "主气": zhu, "客气": ke,
            "主气五行": LIUQI_WX[zhu], "客气五行": LIUQI_WX[ke],
            "起": BU_QI_JIE[j],
            "主气说明": ZHUQI_NOTE[BU_NAMES[j]],
            "加临": "客主同气" if zhu == ke else "客主异气",
        }
        if year:
            step["起日"] = jieqi_solar(year, BU_QI_JIE[j])
        steps.append(step)
    return steps


def current_bu(year: int, month: int, day: int) -> dict:
    """当前日期所在的六步（该步的主气、客气、主气说明、起日）。

    六步周期从每年大寒起算：日期早于本年大寒时，用上一年的干支年与六步（年初 1 月）。
    """
    from datetime import date as _date
    gz = year_yunqi(year)["ganzhi"]
    steps = buqi(gz, year)
    today = _date(year, month, day)
    try:
        first = _date.fromisoformat(steps[0]["起日"])
    except Exception:
        first = _date(year, 1, 21)              # 大寒常在 1 月 20 日前后，兜底
    if today < first:
        gz = year_yunqi(year - 1)["ganzhi"]
        steps = buqi(gz, year - 1)
    cur = None
    for j in range(5, -1, -1):
        s = steps[j]
        try:
            d0 = _date.fromisoformat(s["起日"])
        except Exception:
            continue
        if today >= d0:
            cur = s
            break
    return cur or steps[0]


def jieqi_solar(year: int, name: str):
    """该年某节气的公历日期（用历法库查）。"""
    from lunar_python import Solar
    s = Solar.fromYmdHms(year, 6, 1, 12, 0, 0)
    table = s.getLunar().getJieQiTable()
    jq = table.get(name)
    return jq.toYmd() if jq else ""


def year_yunqi(year: int) -> dict:
    """该公历年的运气（以立春分界的干支年）。"""
    from lunar_python import Solar
    s = Solar.fromYmdHms(year, 6, 1, 12, 0, 0)
    ganzhi = s.getLunar().getEightChar().getYear()
    return yunqi(ganzhi)


def check_pairs_against_rules():
    """内部自检：起法规则算出的中运/司天/在泉必须与转录表一致。返回不一致清单。"""
    bad = []
    for p in PAIRS:
        for y in p["years"]:
            r = yunqi(y)
            if r["中运"]["五音"] != p["yun5"] or r["司天"] != p["si"] or r["在泉"] != p["zai"]:
                bad.append((y, r, p["yun5"], p["si"], p["zai"]))
    return bad


