def _make_city(name, lng, lat, districts_str):
    return {"n": name, "l": lng, "t": lat,
            "d": [{"n": d, "l": lng, "t": lat} for d in districts_str.split("、")]}


def build_extra_provinces() -> list:
    """构建台湾省 + 香港 + 澳门（省级列表，含完整三层结构）"""
    tw_cities = []
    for row in TW_CITIES:
        name, lng, lat, districts = row.split("|")
        tw_cities.append(_make_city(name, float(lng), float(lat), districts))
    taiwan = {"n": "台湾省", "l": 121.0, "t": 23.7, "c": tw_cities}

    hk = {"n": "香港特别行政区", "l": 114.1694, "t": 22.3193,
          "c": [_make_city("市辖区", 114.1694, 22.3193, HK_DISTRICTS)]}
    mo = {"n": "澳门特别行政区", "l": 113.5491, "t": 22.1987,
          "c": [_make_city("市辖区", 113.5491, 22.1987, MO_DISTRICTS)]}
    return [taiwan, hk, mo]


def main():
    data = json.loads(TARGET.read_text(encoding="utf-8"))
    new_names = {"台湾省", "香港特别行政区", "澳门特别行政区"}
    data = [p for p in data if p["n"] not in new_names]
    data.extend(build_extra_provinces())
    TARGET.write_text(json.dumps(data, ensure_ascii=False, separators=(",", ":")), encoding="utf-8")
    total_c = sum(len(p["c"]) for p in data if p["n"] in new_names)
    total_d = sum(len(c["d"]) for p in data if p["n"] in new_names for c in p["c"])
    print(f"已写入：台湾 22 县市 368 区乡镇 + 香港 18 区 + 澳门 8 区；文件省数 {len(data)}")


if __name__ == "__main__":
    main()
