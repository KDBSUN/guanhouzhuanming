# 六、处理声调数据
# ============================================================
def build_tone_data(pingshui_path, cilin_path):
    """从 Pingshui_Rhyme.json 和 Cilin_Rhyme.json 构建声调查询表"""
    tone_map = {}  # char -> tone (平=1, 上=2, 去=3, 入=4)

    # 先加载平水韵（主数据）
    with open(pingshui_path, "r", encoding="utf-8") as f:
        ps = json.load(f)

    for category, groups in ps.items():
        if "平" in category:
            tone = 1  # 平
        elif "上" in category:
            tone = 2  # 上
        elif "去" in category:
            tone = 3  # 去
        elif "入" in category:
            tone = 4  # 入
        else:
            continue

        for group_name, chars in groups.items():
            for ch in chars:
                # 平水韵优先级最高，直接覆盖
                tone_map[ch] = tone

    ps_count = len(tone_map)
    print(f"  [OK] Pingshui tones: {ps_count} chars")

    # 再加载词林正韵（兜底）
    with open(cilin_path, "r", encoding="utf-8") as f:
        cl = json.load(f)

    cl_count = 0
    for category, groups in cl.items():
        for group_name, chars in groups.items():
            if "平" in group_name:
                tone = 1
            elif "上" in group_name:
                tone = 2
            elif "去" in group_name:
                tone = 3
            elif "入" in group_name:
                tone = 4
            elif "仄" in group_name:
                # 词林正韵的仄声包含上去入，统一标记为仄声(用5表示)
                tone = 5
            else:
                continue

            for ch in chars:
                if ch not in tone_map:
                    tone_map[ch] = tone
                    cl_count += 1

    print(f"  [OK] Cilin fallback: {cl_count} chars")
    print(f"  [OK] Total tones: {len(tone_map)} chars")
    return tone_map


