# 三、构建六十四卦完整数据
# ============================================================
def build_hexagram_data():
    """构建六十四卦的完整映射"""
    hexagrams = {}
    # 以 (上卦数, 下卦数) 为 key
    by_key = {}

    # Unicode 六十四卦符号从 U+4DC0 开始，按文王卦序
    unicode_base = 0x4DC0

    for i, (upper, lower, name, order) in enumerate(HEXAGRAM_DEFS):
        symbol = chr(unicode_base + i)
        key = f"{upper},{lower}"

        upper_gua = BAGUA[upper]
        lower_gua = BAGUA[lower]

        entry = {
            "order": order,
            "name": name,
            "name_short": name,
            "upper": {
                "num": upper,
                "name": upper_gua["name"],
                "symbol": upper_gua["symbol"],
                "wuxing": upper_gua["wuxing"],
            },
            "lower": {
                "num": lower,
                "name": lower_gua["name"],
                "symbol": lower_gua["symbol"],
                "wuxing": lower_gua["wuxing"],
            },
            "symbol": symbol,
            "yaoci": YAOCI.get(name, ["爻辞待补充"] * 6),
            "guaci": GUACI.get(name, ""),
            "daxiang": DAXIANG.get(name, ""),
        }

        by_key[key] = entry
        hexagrams[str(order)] = entry

    return {"by_key": by_key, "by_order": hexagrams}


