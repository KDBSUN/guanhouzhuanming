# 五、处理拆字数据 (chaizi-ft.txt)
# ============================================================
def build_chaizi_data(chaizi_path):
    """从 chaizi-ft.txt 构建拆字查询表"""
    chaizi_map = {}
    with open(chaizi_path, "r", encoding="utf-8") as f:
        for line in f:
            line = line.strip()
            if not line:
                continue
            parts = line.split("\t")
            char = parts[0].strip()
            if len(parts) > 1:
                # 每个拆法是一个字符串，用空格分隔部件
                decompositions = []
                for comp_str in parts[1:]:
                    comps = comp_str.strip().split()
                    decompositions.append(comps)
                chaizi_map[char] = decompositions
            else:
                chaizi_map[char] = []

    print(f"  [OK] Chaizi data: {len(chaizi_map)} chars")
    return chaizi_map


