# 四、处理笔画数据 (Content.xlsx)
# ============================================================
def build_stroke_data(xlsx_path):
    """从 Content.xlsx 构建笔画查询表"""
    wb = openpyxl.load_workbook(xlsx_path)
    ws = wb.active

    stroke_map = {}  # char -> ftbh
    count = 0

    for row in ws.iter_rows(min_row=2, values_only=True):
        if row[1] and row[9]:  # jtz (column B) and ftbh (column J)
            char = str(row[1]).strip()
            try:
                ftbh = int(row[9])
                stroke_map[char] = ftbh
                count += 1
            except (ValueError, TypeError):
                pass

    print(f"  [OK] Stroke data: {count} chars")
    return stroke_map


